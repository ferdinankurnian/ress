const result = await Bun.build({
  entrypoints: ["src/reader/extract.browser.ts"],
  target: "browser", format: "iife", minify: true,
});
if (!result.success) throw new Error(result.logs.join("\n"));
const notice = await Bun.file("node_modules/@mozilla/readability/LICENSE.md").text();
const script = `/* Mozilla Readability\n${notice}\n*/\n${await result.outputs[0].text()}`;
await Bun.write("src/reader/extraction.generated.ts",
  `// Generated by bun scripts/build-reader.ts. Includes Mozilla Readability (Apache-2.0).\nexport const extractionScript = ${JSON.stringify(script + "\ntrue;")};\n`);
export {};
